package com.scrollcontrol.app.service

import android.accessibilityservice.AccessibilityService
import android.accessibilityservice.AccessibilityServiceInfo
import android.content.Intent
import android.graphics.Rect
import android.net.Uri
import android.os.Build
import android.util.Log
import android.view.KeyEvent
import android.view.accessibility.AccessibilityEvent
import android.view.accessibility.AccessibilityNodeInfo
import com.scrollcontrol.app.ScrollControlApp
import com.scrollcontrol.app.data.BlockerSettings
import com.scrollcontrol.app.ui.BlockActivity
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.Job
import kotlinx.coroutines.flow.collectLatest
import kotlinx.coroutines.launch

class InstagramReelsBlockerService : AccessibilityService() {

    private val serviceScope = CoroutineScope(Dispatchers.Main + Job())
    private var currentSettings = BlockerSettings()
    private var lastBlockScreenTimestamp: Long = 0
    private lateinit var overlayManager: OverlayPopupManager

    companion object {
        private const val TAG = "ScrollControlService"
        private const val BLOCK_COOLDOWN_MS = 2000L

        var isServiceRunning: Boolean = false
            private set

        // Grace window (e.g. 4 seconds) to let user switch back to Feed or DMs safely
        var suppressBlockingUntil: Long = 0L

        // Set to true when user taps "Back to Feed" or "Back to DMs" so the service auto-taps the Home tab
        var pendingNavigateToHome: Boolean = false

        // Instance pointer for direct dashboard preview testing of the overlay window
        var instance: InstagramReelsBlockerService? = null
            private set
    }

    override fun onServiceConnected() {
        super.onServiceConnected()

        val info = serviceInfo ?: AccessibilityServiceInfo()
        info.eventTypes = AccessibilityEvent.TYPES_ALL_MASK
        info.feedbackType = AccessibilityServiceInfo.FEEDBACK_GENERIC
        info.flags = AccessibilityServiceInfo.FLAG_REPORT_VIEW_IDS or
                AccessibilityServiceInfo.FLAG_RETRIEVE_INTERACTIVE_WINDOWS or
                AccessibilityServiceInfo.FLAG_INCLUDE_NOT_IMPORTANT_VIEWS or
                AccessibilityServiceInfo.FLAG_REQUEST_FILTER_KEY_EVENTS
        info.notificationTimeout = 50
        this.serviceInfo = info

        overlayManager = OverlayPopupManager(this)
        instance = this
        isServiceRunning = true
        Log.d(TAG, "ScrollControl Service connected with Floating Overlay Window.")

        serviceScope.launch {
            ScrollControlApp.instance.preferencesRepository.settingsFlow.collectLatest { settings ->
                currentSettings = settings
            }
        }
    }

    override fun onAccessibilityEvent(event: AccessibilityEvent?) {
        if (event == null || !currentSettings.isBlockerEnabled) return

        val packageName = event.packageName?.toString() ?: return

        // 1. Never react to events generated by our own overlay window
        if (packageName == applicationContext.packageName) {
            return
        }

        // 2. If the overlay is already displayed, keep it stable and do not re-trigger or auto-dismiss
        if (::overlayManager.isInitialized && overlayManager.isShowing) {
            // Dismiss only if the user explicitly switched away to their home screen launcher
            if (isHomeLauncherPackage(packageName)) {
                overlayManager.hide()
            }
            return
        }

        // 3. Only process Instagram events
        if (!packageName.contains("instagram", ignoreCase = true)) {
            return
        }

        val rootNode = rootInActiveWindow ?: return

        // Compute actual active window dimensions and density-aware thresholds
        val windowBounds = Rect()
        rootNode.getBoundsInScreen(windowBounds)
        val windowBottom = if (windowBounds.bottom > 0) windowBounds.bottom else resources.displayMetrics.heightPixels
        val windowWidth = if (windowBounds.width() > 0) windowBounds.width() else resources.displayMetrics.widthPixels
        val density = resources.displayMetrics.density

        // Bottom nav bar threshold: within bottom 22% of screen
        val bottomBarMinY = (windowBottom * 0.78f).toInt()
        val minTabHeightPx = (20 * density).toInt()
        val maxTabHeightPx = (140 * density).toInt()
        val maxTabWidthPx = (windowWidth * 0.40f).toInt()

        // If resuming from Scrolling Lock, auto-switch to Home tab to unselect Reels
        if (pendingNavigateToHome) {
            val homeTab = findHomeTabNode(rootNode, 0, bottomBarMinY)
            if (homeTab != null) {
                if (homeTab.isClickable) {
                    homeTab.performAction(AccessibilityNodeInfo.ACTION_CLICK)
                } else {
                    homeTab.parent?.performAction(AccessibilityNodeInfo.ACTION_CLICK)
                }
                pendingNavigateToHome = false
                Log.d(TAG, "Switched away from Reels to Home tab.")
            }
        }

        when (event.eventType) {
            AccessibilityEvent.TYPE_VIEW_CLICKED -> {
                handleViewClicked(
                    event = event,
                    bottomBarMinY = bottomBarMinY,
                    minTabHeightPx = minTabHeightPx,
                    maxTabHeightPx = maxTabHeightPx,
                    maxTabWidthPx = maxTabWidthPx
                )
            }
            AccessibilityEvent.TYPE_WINDOW_STATE_CHANGED,
            AccessibilityEvent.TYPE_WINDOW_CONTENT_CHANGED,
            AccessibilityEvent.TYPE_VIEW_SCROLLED,
            AccessibilityEvent.TYPE_VIEW_SELECTED -> {
                handleScreenContent(
                    rootNode = rootNode,
                    bottomBarMinY = bottomBarMinY,
                    minTabHeightPx = minTabHeightPx,
                    maxTabHeightPx = maxTabHeightPx,
                    maxTabWidthPx = maxTabWidthPx
                )
            }
        }
    }

    private fun isHomeLauncherPackage(pkg: String): Boolean {
        val lower = pkg.lowercase()
        return lower.contains("launcher") || lower.contains("home")
    }

    /**
     * Intercept click on the Reels tab in the bottom navigation bar.
     */
    private fun handleViewClicked(
        event: AccessibilityEvent,
        bottomBarMinY: Int,
        minTabHeightPx: Int,
        maxTabHeightPx: Int,
        maxTabWidthPx: Int
    ) {
        if (System.currentTimeMillis() < suppressBlockingUntil) return

        val contentDesc = event.contentDescription?.toString() ?: ""
        val sourceNode = event.source ?: return

        // Exclude messages, sent cards, or previews in chat
        if (isChatMessageOrPreview(contentDesc)) {
            return
        }

        val isReelsDesc = isReelsIdentifier(contentDesc, sourceNode.viewIdResourceName)

        if (isReelsDesc) {
            val bounds = Rect()
            sourceNode.getBoundsInScreen(bounds)

            // Must be in bottom navigation bar
            val isAtBottomNav = bounds.bottom >= bottomBarMinY &&
                    bounds.height() in minTabHeightPx..maxTabHeightPx &&
                    bounds.width() <= maxTabWidthPx

            if (isAtBottomNav) {
                Log.d(TAG, "Reels tab click detected! Showing Truecaller-style Overlay.")
                showScrollingLock(BlockActivity.REASON_REELS_TAB)
            }
        }
    }

    /**
     * Inspect screen content for:
     * 1. DM Reel scrolling via the "Send to chat" pill button.
     * 2. Reels Tab Pill engagement (Image 1 engaged state in bottom navigation bar).
     */
    private fun handleScreenContent(
        rootNode: AccessibilityNodeInfo,
        bottomBarMinY: Int,
        minTabHeightPx: Int,
        maxTabHeightPx: Int,
        maxTabWidthPx: Int
    ) {
        if (System.currentTimeMillis() < suppressBlockingUntil) return

        // Check 1: DM Reel scrolling via "Send to chat" button
        if (currentSettings.blockNextReelScrollInDm && hasSendToChatButton(rootNode)) {
            Log.d(TAG, "DM Reel scrolling detected via 'Send to chat' button! Showing Truecaller-style Overlay.")
            showScrollingLock(BlockActivity.REASON_DM_SCROLL)
            return
        }

        // Check 2: Engaged Reels tab pill in bottom navigation bar
        if (isReelsPillEngaged(
                node = rootNode,
                depth = 0,
                bottomBarMinY = bottomBarMinY,
                minTabHeightPx = minTabHeightPx,
                maxTabHeightPx = maxTabHeightPx,
                maxTabWidthPx = maxTabWidthPx
            )
        ) {
            Log.d(TAG, "Engaged Reels tab pill detected! Showing Truecaller-style Overlay.")
            showScrollingLock(BlockActivity.REASON_REELS_TAB)
        }
    }

    /**
     * Detects the floating "Send to chat" button (with avatar) that appears when you
     * start scrolling reels from a Direct Message.
     */
    private fun hasSendToChatButton(node: AccessibilityNodeInfo?, depth: Int = 0): Boolean {
        if (node == null || depth > 25) return false

        val text = node.text?.toString() ?: ""
        val desc = node.contentDescription?.toString() ?: ""
        val viewId = node.viewIdResourceName ?: ""

        if (isSendToChatText(text) || isSendToChatText(desc) || isSendToChatViewId(viewId)) {
            return true
        }

        for (i in 0 until node.childCount) {
            if (hasSendToChatButton(node.getChild(i), depth + 1)) {
                return true
            }
        }
        return false
    }

    private fun isSendToChatText(str: String): Boolean {
        if (str.isEmpty()) return false
        val lower = str.lowercase().trim()
        return lower == "send to chat" ||
                lower == "send in chat" ||
                lower.startsWith("send to chat") ||
                lower.startsWith("send in chat") ||
                lower.contains("send to chat") ||
                (lower.startsWith("send to ") && lower.length < 35)
    }

    private fun isSendToChatViewId(viewId: String): Boolean {
        if (viewId.isEmpty()) return false
        val lower = viewId.lowercase()
        return lower.contains("send_to_chat") ||
                lower.contains("clips_quick_share") ||
                lower.contains("direct_share_to_chat") ||
                lower.contains("share_to_chat")
    }

    /**
     * PURE REELS TAB PILL LOGIC:
     * - Engaged state (Image 1): The rounded pill capsule container is active around the Reels play icon.
     * - Unengaged state (Image 2): Plain outline icon (isSelected == false).
     */
    private fun isReelsPillEngaged(
        node: AccessibilityNodeInfo?,
        depth: Int,
        bottomBarMinY: Int,
        minTabHeightPx: Int,
        maxTabHeightPx: Int,
        maxTabWidthPx: Int
    ): Boolean {
        if (node == null || depth > 25) return false

        val desc = node.contentDescription?.toString() ?: ""

        // Exclude chat messages, sent reels, user handles, or media previews
        if (isChatMessageOrPreview(desc)) {
            return false
        }

        val bounds = Rect()
        node.getBoundsInScreen(bounds)

        // Strict bottom navigation bar coordinates
        val isAtBottomNav = bounds.bottom >= bottomBarMinY &&
                bounds.height() in minTabHeightPx..maxTabHeightPx &&
                bounds.width() <= maxTabWidthPx

        if (isAtBottomNav) {
            val isReelsTab = isReelsIdentifier(desc, node.viewIdResourceName)

            if (isReelsTab) {
                val stateDesc = if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.R) {
                    node.stateDescription?.toString() ?: ""
                } else ""

                // The pill container (Image 1 engaged state) marks the tab as selected/active
                val isPillEngaged = node.isSelected ||
                        node.parent?.isSelected == true ||
                        hasSelectedChild(node) ||
                        stateDesc.contains("selected", ignoreCase = true) ||
                        stateDesc.contains("active", ignoreCase = true) ||
                        desc.contains("selected", ignoreCase = true) ||
                        desc.contains("active", ignoreCase = true) ||
                        isPillViewId(node.viewIdResourceName)

                if (isPillEngaged) {
                    return true
                }
            }
        }

        for (i in 0 until node.childCount) {
            if (isReelsPillEngaged(
                    node = node.getChild(i),
                    depth = depth + 1,
                    bottomBarMinY = bottomBarMinY,
                    minTabHeightPx = minTabHeightPx,
                    maxTabHeightPx = maxTabHeightPx,
                    maxTabWidthPx = maxTabWidthPx
                )
            ) {
                return true
            }
        }
        return false
    }

    private fun hasSelectedChild(node: AccessibilityNodeInfo): Boolean {
        for (i in 0 until node.childCount) {
            val child = node.getChild(i) ?: continue
            if (child.isSelected) return true
        }
        return false
    }

    private fun isChatMessageOrPreview(desc: String): Boolean {
        if (desc.isEmpty()) return false
        val lower = desc.lowercase()
        return lower.contains("by ") ||
                lower.contains("shared ") ||
                lower.contains("sent ") ||
                lower.contains("watch ") ||
                lower.contains("reply") ||
                lower.contains("photo by") ||
                lower.contains("video by") ||
                lower.contains("audio by")
    }

    private fun isReelsIdentifier(desc: String, viewId: String?): Boolean {
        val lowerDesc = desc.lowercase().trim()
        val isDescMatch = lowerDesc == "reels" ||
                lowerDesc == "reels tab" ||
                lowerDesc.startsWith("reels") ||
                lowerDesc.contains("selected, reels") ||
                lowerDesc.contains("reels, selected")

        val isViewIdMatch = viewId?.contains("clips_tab", ignoreCase = true) == true ||
                viewId?.contains("reels_tab", ignoreCase = true) == true

        return isDescMatch || isViewIdMatch
    }

    private fun isPillViewId(viewId: String?): Boolean {
        if (viewId == null) return false
        val lower = viewId.lowercase()
        return lower.contains("pill") || lower.contains("indicator") || lower.contains("active_tab")
    }

    private fun findHomeTabNode(node: AccessibilityNodeInfo?, depth: Int, bottomBarMinY: Int): AccessibilityNodeInfo? {
        if (node == null || depth > 25) return null
        val desc = node.contentDescription?.toString() ?: ""
        val isHomeDesc = desc.equals("Home", ignoreCase = true) ||
                desc.equals("Feed", ignoreCase = true) ||
                desc.startsWith("Home", ignoreCase = true)

        if (isHomeDesc) {
            val bounds = Rect()
            node.getBoundsInScreen(bounds)
            if (bounds.bottom >= bottomBarMinY) {
                return node
            }
        }
        for (i in 0 until node.childCount) {
            val res = findHomeTabNode(node.getChild(i), depth + 1, bottomBarMinY)
            if (res != null) return res
        }
        return null
    }

    /**
     * Shows the floating overlay window directly over Instagram (Truecaller style),
     * pausing video/audio playback and completely blocking scrolling touches.
     */
    fun showScrollingLock(reason: String) {
        val now = System.currentTimeMillis()
        if (now - lastBlockScreenTimestamp < BLOCK_COOLDOWN_MS) {
            return
        }
        lastBlockScreenTimestamp = now

        try {
            if (::overlayManager.isInitialized) {
                overlayManager.show(
                    reason = reason,
                    onGoToDms = { openInstagramDms() },
                    onGoToFeed = { openInstagramFeed() },
                    onGoHome = { goToHomeScreen() }
                )
                incrementBlockedCounter()
            } else {
                val intent = Intent(this, BlockActivity::class.java).apply {
                    flags = Intent.FLAG_ACTIVITY_NEW_TASK or Intent.FLAG_ACTIVITY_SINGLE_TOP
                    putExtra(BlockActivity.EXTRA_BLOCK_REASON, reason)
                }
                startActivity(intent)
                incrementBlockedCounter()
            }
        } catch (e: Exception) {
            Log.e(TAG, "Error displaying scrolling lock overlay", e)
        }
    }

    private fun openInstagramDms() {
        suppressBlockingUntil = System.currentTimeMillis() + 4000L
        pendingNavigateToHome = true

        try {
            val dmIntent = Intent(Intent.ACTION_VIEW, Uri.parse("instagram://direct-inbox")).apply {
                setPackage("com.instagram.android")
                flags = Intent.FLAG_ACTIVITY_NEW_TASK
            }
            startActivity(dmIntent)
        } catch (e: Exception) {
            val launchIntent = packageManager.getLaunchIntentForPackage("com.instagram.android")?.apply {
                flags = Intent.FLAG_ACTIVITY_NEW_TASK or Intent.FLAG_ACTIVITY_RESET_TASK_IF_NEEDED
            }
            if (launchIntent != null) {
                startActivity(launchIntent)
            }
        }
    }

    private fun openInstagramFeed() {
        // Pause blocker for 5 seconds so user can browse posts on the Home feed without re-locking
        suppressBlockingUntil = System.currentTimeMillis() + 5000L
        pendingNavigateToHome = true
        try {
            val launchIntent = packageManager.getLaunchIntentForPackage("com.instagram.android")?.apply {
                flags = Intent.FLAG_ACTIVITY_NEW_TASK or Intent.FLAG_ACTIVITY_RESET_TASK_IF_NEEDED
            }
            if (launchIntent != null) {
                startActivity(launchIntent)
            }
        } catch (e: Exception) {
            // ignore
        }
    }

    private fun goToHomeScreen() {
        performGlobalAction(GLOBAL_ACTION_HOME)
    }

    override fun onKeyEvent(event: KeyEvent?): Boolean {
        if (::overlayManager.isInitialized && overlayManager.isShowing && event?.keyCode == KeyEvent.KEYCODE_BACK && event.action == KeyEvent.ACTION_UP) {
            overlayManager.hide()
            performGlobalAction(GLOBAL_ACTION_HOME)
            return true
        }
        return super.onKeyEvent(event)
    }

    private fun incrementBlockedCounter() {
        serviceScope.launch {
            ScrollControlApp.instance.preferencesRepository.incrementReelsBlockedCount()
        }
    }

    override fun onInterrupt() {
        Log.d(TAG, "ScrollControl Service interrupted.")
    }

    override fun onDestroy() {
        super.onDestroy()
        if (::overlayManager.isInitialized) {
            overlayManager.hide()
        }
        instance = null
        isServiceRunning = false
        Log.d(TAG, "ScrollControl Service destroyed.")
    }
}
